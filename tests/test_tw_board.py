@pytest.mark.skipif(not os.path.exists(tb.BOARD_FILE), reason="board not built yet")
def test_every_galactic_legend_has_a_territory_war_squad():
    """The complaint that triggered this rebuild: four GLs — JMK, JML, Jabba and GL
    Ahsoka — were on no TW squad at all, so 20 of the account's best units sat idle
    while filler banked the same +30."""
    b = json.load(open(tb.BOARD_FILE))
    own, _ = tb.load_roster()
    placed = set(tb.validate(b, own)[2])
    gls = {"JABBATHEHUTT", "GLREY", "GLLEIA", "GLAHSOKATANO", "JEDIMASTERKENOBI",
           "SUPREMELEADERKYLOREN", "SITHPALPATINE", "LORDVADER", "GRANDMASTERLUKE"}
    assert gls <= placed, f"GLs with no TW squad: {sorted(gls - placed)}"


@pytest.mark.skipif(not os.path.exists(tb.BOARD_FILE), reason="board not built yet")
def test_every_squad_records_why_it_is_there():
    """A board nobody can audit is the one that drifts back into faction-tag filler."""
    b = json.load(open(tb.BOARD_FILE))
    for s in b.get("defense", []):
        assert s.get("why"), f"{s.get('id')} has no rationale"
    for s in b.get("offense", []):
        assert s.get("for"), f"{s.get('id')} does not say what it attacks"
